# Assignment: Summer times
# Create a program using conditional statements

print("Welcome to the Summer Times program!")
temperature = float(input("Enter the current temperature in Celsius: "))

if temperature > 25:
    print("It's hot outside! It feels like summer.")
    print("Perfect weather for swimming and ice cream!")
else:
    print("It's not that hot today.")
    print("You might want to wear a light jacket or stay cozy indoors.")
